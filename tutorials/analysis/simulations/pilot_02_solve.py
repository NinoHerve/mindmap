"""
Pilot study step 4b/5: solve all 6 inverse methods on every run of the pilot
dataset (sub-simf10-pilot, generated by pilot_01_generate.py) and extract the
three outcome measures per (region, repetition, method):
  - localization error at hrp (peak localization error, same convention as
    inverse-noisesweep.ipynb)
  - average precision (AP) at hrp and pp (two-timepoint PR curve)
  - spatial correlation to gold over ~50 evenly-spaced time points across the
    signal window, reduced to a scalar AUC-over-time summary for the power
    analysis, with the raw 50-point curve also kept (for the secondary
    cluster-based permutation test mentioned in the task spec, not run here)

All three solved together in one call to each method's `.solve()`, on a single
phase_data array whose columns are the union of {hrp_idx, pp_idx} and 50
evenly-spaced indices across signal_window -- avoids solving twice.

Checkpointed per run: writes `pilot_metrics/run-{run:03d}.json` (scalar rows,
one per method) and `pilot_metrics/run-{run:03d}_curves.npz` (raw 50-point
correlation curves, one array per method) immediately after that run's own
solve, so a crash partway through only loses runs not yet started -- rerunning
this script skips any run whose output files already exist.
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
import mne

import mindmap as mm
from mindmap.analysis.functional.inverse import (
    InverseSimTask, build_phase_data_hrp_pp_curve, score_source_reconstruction,
)
from mindmap.tasks import run_parallel_pipeline

N_CURVE_POINTS = 50
N_JOBS = 8

dm = mm.io.TutoManager("../../config.yml")
sub = "simf10"
sub_pilot = "simf10-pilot"

fwd = dm.load(sub, "fwd", desc="inv")
eig = dm.load(sub, "eig")
dipole_positions = mm.anatomy.source_space.get_dipole_positions(fwd["src"]) * 1000

simulator_dir = dm.roots["sim"] / f"sub-{sub_pilot}" / "simulator"

metrics_dir = Path("pilot_metrics")
metrics_dir.mkdir(exist_ok=True)

df_index = pd.read_csv(dm.roots["sim"] / f"sub-{sub_pilot}" / "simulation_index.tsv", sep="\t")


def preprocess_curve(ctx):
    """Builds phase_data on the union of {hrp_idx, pp_idx} + N_CURVE_POINTS
    evenly-spaced indices across gold's own active-signal duration -- see
    `build_phase_data_hrp_pp_curve` (extracted here so every pilot study can
    reuse the same hrp/pp/curve timepoint logic instead of re-inlining it).
    """
    return build_phase_data_hrp_pp_curve(
        ctx["ave"], ctx["gold"], ctx["simulator"], n_curve_points=N_CURVE_POINTS,
    )


def reconstruct(ctx):
    data, ncov = ctx["phase_data"], ctx["ncov"]

    snr, _ = mm.analysis.eeg.estimate_evoked_snr(
        evoked=ctx["ave"], baseline=ctx["simulator"].epoch_config.baseline, noise_cov=ncov)
    lambda2_auto = max(0.01, 1.0 / (snr.max() ** 2))

    inv_wcset = mm.analysis.inverse.wCSET(
        forward=fwd, noise_cov=ncov, depth=0.5,
        eigenvectors=eig["vec"], eigenvalues=eig["val"], harm=5, harmonic_method="lowpass",
    )
    inv_cset = mm.analysis.inverse.CSET(forward=fwd, noise_cov=ncov, depth=0.8, eigenvectors=eig["vec"])
    inv_mce = mm.analysis.inverse.MCE(forward=fwd, noise_cov=ncov, depth=0.8)
    inv_mne_op = mne.minimum_norm.make_inverse_operator(
        info=data.info, forward=fwd, noise_cov=ncov, fixed=True, depth=None, verbose="warning",
    )

    solutions = {
        "wcset": inv_wcset.solve(data, lambda2_auto),
        "cset": inv_cset.solve(data, lambda2=0.1),
        "mce": inv_mce.solve(data, lambda2=0.1),
    }
    for m, mne_name in {"sloreta": "sLORETA", "dspm": "dSPM", "mne": "MNE"}.items():
        solutions[m] = mne.minimum_norm.apply_inverse(data, inv_mne_op, lambda2_auto, method=mne_name, verbose="warning")

    return {"solutions": solutions}


def postprocess_and_checkpoint(ctx):
    gold, task, src = ctx["gold"], ctx["task"], ctx["src"]

    true_source_mask = src.select_targets(
        ctx["simulator"].hm.src, ctx["simulator"].hm.parc, ctx["simulator"].hm.ras2tkras,
    )

    scores = score_source_reconstruction(
        gold=gold,
        solutions=ctx["solutions"],
        hrp_idx=ctx["hrp_idx"], pp_idx=ctx["pp_idx"], curve_idx=ctx["curve_idx"],
        hrp_col=ctx["hrp_col"], pp_col=ctx["pp_col"], curve_cols=ctx["curve_cols"],
        true_source_mask=true_source_mask, dipole_positions=dipole_positions,
    )

    rows = []
    curves = {}
    for method, s in scores.items():
        curves[method] = s.pop("correlation_curve")
        rows.append({"run": task.run, "method": method, **s})

    with open(metrics_dir / f"run-{task.run:03d}.json", "w") as f:
        json.dump(rows, f)
    np.savez(metrics_dir / f"run-{task.run:03d}_curves.npz", **curves)

    return rows


tasks = []
for _, row in df_index.iterrows():
    run = int(row["run"])
    if (metrics_dir / f"run-{run:03d}.json").exists():
        continue     # checkpoint hit -- already solved
    tasks.append(InverseSimTask(
        run=run,
        simulator_dir=simulator_dir,
        fave=dm.get_path(sub_pilot, "ave", run=run),
        fcov=dm.get_path(sub_pilot, "cov", run=run),
        fgold=dm.get_path(sub_pilot, "gold", run=run),
        fsource=dm.get_path(sub_pilot, "source", run=run),
        target_snr=row["target_snr"],
    ))

print(f"{len(tasks)} runs left to solve (of {len(df_index)} total; "
      f"{len(df_index) - len(tasks)} already checkpointed).")

if tasks:
    run_parallel_pipeline(tasks, preprocess_curve, reconstruct, postprocess_and_checkpoint, n_jobs=N_JOBS, n_threads_per_job=1)

print("Done.")
